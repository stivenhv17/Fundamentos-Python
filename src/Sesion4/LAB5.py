# Operaciones con variables
# Creamos nuevas variables
rojas = 8
verdes = 4

print("Manzanas rojas:", rojas)
print("Manzanas verdes:", verdes)

print("Suma:", rojas + verdes)# Suma
print("Resta:", rojas - verdes)# Resta
print("Multiplicación:", rojas * verdes)# Multiplicación
print("División:", rojas / verdes)# División
print("División entera:", rojas // verdes)# División entera
print("Residuo:", rojas % verdes)# Residuo
print("Potencia:", rojas ** 2) # Potencia